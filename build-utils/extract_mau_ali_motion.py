#!/usr/bin/env python3
"""Extract the author's complete selection tracks without retiming/attenuation.

Mau Ali / Lottie Simple License FL 9.13.21. Original archive remains bundled.
Only application icons and the selection's destination coordinates are adapted.
"""
import hashlib
import json
import sys
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def extract():
    archive = ROOT / 'assets/data/mau-ali-tab-menu.lottie'
    with zipfile.ZipFile(archive) as z:
        scene = json.loads(z.read('a/Main Scene.json'))
    layers = {layer['nm']: layer for layer in scene['layers']}
    shapes = layers['Selected 2']['shapes'][0]['it']
    path = next(s for s in shapes if s['ty'] == 'sh')
    stroke = next(s for s in shapes if s['ty'] == 'gs')
    fill = next(s for s in shapes if s['ty'] == 'fl')
    data = {
        'creator': 'Mau Ali',
        'source': 'https://lottiefiles.com/free-animation/free-interactive-ios-26-inspired-tab-menu-uTAhrmTC08',
        'license': 'Lottie Simple License FL 9.13.21',
        'sha256': hashlib.sha256(archive.read_bytes()).hexdigest(),
        'fps': scene['fr'],
        'segments': [m for m in scene['markers'] if m['dr'] >= 32],
        'tracks': {
            'position': layers['Select_mover']['ks']['p'],
            'scale': layers['Selected 2']['ks']['s'],
            'path': path['ks'],
            'container': layers['Container']['ks']['s'],
            'rimStart': stroke['s'],
            'rimEnd': stroke['e'],
            'rimOpacity': stroke['o'],
            'fillOpacity': fill['o'],
        },
        'adaptation': 'All original selection segments, frame timings, Bezier contour, full scale, capsule pulse and moving rim; only icon content and destination geometry are retargeted to visible application tabs.',
    }
    encoded = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
    if '--check' in sys.argv:
        assert json.loads((ROOT / 'assets/data/mau-ali-tab-motion.json').read_text()) == data
        source = (ROOT / 'lib/widgets/mau_ali_tab_motion_data.dart').read_text()
        payload = source.split("r" + "'" * 3, 1)[1].rsplit("'" * 3, 1)[0]
        assert json.loads(payload) == data
        print(f'PASS all {len(data["segments"])} original selection segments; full timing and unattenuated tracks.')
        return
    (ROOT / 'assets/data/mau-ali-tab-motion.json').write_text(encoded + '\n')
    (ROOT / 'lib/widgets/mau_ali_tab_motion_data.dart').write_text(
        '// Generated by build-utils/extract_mau_ali_motion.py.\n'
        '// Mau Ali, Lottie Simple License FL 9.13.21.\n'
        "const mauAliSelectionSource = r'''" + encoded + "''';\n")
    print(f'Extracted {len(data["segments"])} complete author segments at {scene["fr"]} fps.')


if __name__ == '__main__':
    extract()

  static String text(BuildContext context, String key) =>
      forLocale(Localizations.localeOf(context), key);

  static String forLocale(Locale locale, String key) =>
      _values[localeKey(locale)]?[key] ?? _values['en']![key] ?? key;

  /// Replaces `{name}` placeholders.
  static String format(BuildContext context, String key, Map<String, Object?> values) {
    var result = text(context, key);
    values.forEach((name, value) => result = result.replaceAll('{$name}', '$value'));
    return result;
  }

  static String localeKey(Locale locale) {
    if (locale.languageCode == 'zh') {
      final script = locale.scriptCode?.toLowerCase();
      final country = locale.countryCode?.toUpperCase();
      if (script == 'hant' || country == 'TW' || country == 'HK' || country == 'MO') {
        return 'zh_Hant';
      }
      return 'zh';
    }
    return _values.containsKey(locale.languageCode) ? locale.languageCode : 'en';
  }


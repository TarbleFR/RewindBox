  /// Catalog key for a Flutter locale; a Traditional Chinese script or a
  /// Taiwan, Hong Kong or Macau region selects `zh_Hant`.
  static String localeKey(Locale locale) {
    final language = locale.languageCode;
    if (language == 'zh_Hant') return 'zh_Hant';
    if (language == 'zh') {
      final script = locale.scriptCode?.toLowerCase();
      final country = locale.countryCode?.toUpperCase();
      if (script == 'hant' ||
          country == 'TW' ||
          country == 'HK' ||
          country == 'MO') {
        return 'zh_Hant';
      }
      return 'zh';
    }
    return values.containsKey(language) ? language : 'en';
  }

  static String forLocale(Locale locale, String key) =>
      values[localeKey(locale)]?[key] ?? values['en']![key] ?? key;

  static String formatLocale(
    Locale locale,
    String key,
    Map<String, Object?> arguments,
  ) {
    var value = forLocale(locale, key);
    for (final entry in arguments.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value?.toString() ?? '');
    }
    return value;
  }

  static String text(BuildContext context, String key) => forLocale(
    Localizations.maybeLocaleOf(context) ?? const Locale('en'),
    key,
  );

  static String format(
    BuildContext context,
    String key,
    Map<String, Object?> arguments,
  ) => formatLocale(
    Localizations.maybeLocaleOf(context) ?? const Locale('en'),
    key,
    arguments,
  );

  /// `zh_Hant` for Traditional Chinese (script Hant, or Taiwan, Hong Kong, Macao); English outside the 12 locales.
  static String codeFor(Locale locale) {
    var code = locale.languageCode;
    if (code == 'zh') {
      final script = locale.scriptCode?.toLowerCase();
      final country = locale.countryCode?.toUpperCase();
      if (script == 'hant' || country == 'TW' || country == 'HK' || country == 'MO') code = 'zh_Hant';
    }
    return values.containsKey(code) ? code : 'en';
  }

  static String forLocale(Locale locale, String key) => values[codeFor(locale)]?[key] ?? values['en']![key] ?? key;

  /// Every `menu.*` key (plus `lang.<SystemLanguage>`) resolved for the locale [code], as sent to the native menu.
  static Map<String, String> menuStrings(String code) {
    final table = values[code] ?? values['en']!;
    final english = values['en']!;
    String lookup(String key) => table[key] ?? english[key] ?? key;
    return <String, String>{
      for (final key in table.keys.where((key) => key.startsWith('menu.'))) key: lookup(key),
      for (final key in menuSharedKeys) 'menu.$key': lookup(key),
      for (final entry in languageNames.entries) 'lang.${entry.key}': entry.value,
    };
  }

  static String text(BuildContext context, String key) =>
      forLocale(Localizations.maybeLocaleOf(context) ?? const Locale('en'), key);

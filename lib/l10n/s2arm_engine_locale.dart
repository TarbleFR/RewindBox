  /// The message for [key] in [locale], falling back to English and then to the generic launch failure.
  static String text(Locale locale, String key) {
    final traditional = locale.languageCode == 'zh' &&
        (locale.scriptCode == 'Hant' || const {'TW', 'HK', 'MO'}.contains(locale.countryCode));
    final messages = values[traditional ? 'zh_Hant' : locale.languageCode] ?? values['en']!;
    return messages[key] ?? values['en']![key] ?? messages['launchFailed'] ?? values['en']!['launchFailed']!;
  }

  static String text(BuildContext context, String key, [Map<String, Object?> parameters = const {}]) {
    final locale = Localizations.localeOf(context);
    final traditional = locale.languageCode == 'zh' &&
        (locale.scriptCode == 'Hant' || const {'TW', 'HK', 'MO'}.contains(locale.countryCode));
    var text = (values[traditional ? 'zh_Hant' : locale.languageCode] ?? values['en']!)[key] ?? values['en']![key] ?? key;
    parameters.forEach((name, value) => text = text.replaceAll('{$name}', '${value ?? ''}'));
    return text;
  }

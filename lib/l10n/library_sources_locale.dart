/// Texts of the Library sources section, the catalogue preview and the
/// online title page, in NeoStation's twelve languages. Source names, site
/// labels, URLs, HTTP codes and exception texts are never translated: the
/// screens show them separately as technical details.
abstract final class LibrarySourcesLocale {
  /// Key of the translated explanation of a network failure.
  static String networkKey(LibraryNetworkErrorKind kind) => switch (kind) {
    LibraryNetworkErrorKind.offline => 'netOffline',
    LibraryNetworkErrorKind.timeout => 'netTimeout',
    LibraryNetworkErrorKind.cancelled => 'netCancelled',
    LibraryNetworkErrorKind.challenge => 'netChallenge',
    LibraryNetworkErrorKind.serverUnavailable => 'netServerUnavailable',
    LibraryNetworkErrorKind.notFound => 'netNotFound',
    LibraryNetworkErrorKind.httpStatus => 'netHttpStatus',
    LibraryNetworkErrorKind.tooLarge => 'netTooLarge',
    LibraryNetworkErrorKind.invalidResponse => 'netInvalidResponse',
  };

  /// Key of the translated explanation of a source failure.
  static String sourceErrorKey(LibrarySourceErrorKind kind) => switch (kind) {
    LibrarySourceErrorKind.unsupported => 'srcUnsupported',
    LibrarySourceErrorKind.noResults => 'srcNoResults',
    LibrarySourceErrorKind.noChapters => 'srcNoChapters',
    LibrarySourceErrorKind.noPages => 'srcNoPages',
    LibrarySourceErrorKind.protectedChapter => 'srcProtectedChapter',
    LibrarySourceErrorKind.parseFailed => 'srcParseFailed',
    LibrarySourceErrorKind.invalidImage => 'srcInvalidImage',
    LibrarySourceErrorKind.network => 'errorUnknown',
  };

  /// Key of the translated explanation of a catalogue failure.
  static String catalogErrorKey(LibraryCatalogErrorKind kind) => switch (kind) {
    LibraryCatalogErrorKind.invalidUrl => 'catInvalidUrl',
    LibraryCatalogErrorKind.notHttps => 'catNotHttps',
    LibraryCatalogErrorKind.notFound => 'catNotFound',
    LibraryCatalogErrorKind.invalidDocument => 'catInvalidDocument',
    LibraryCatalogErrorKind.unsupportedFormat => 'catUnsupportedFormat',
    LibraryCatalogErrorKind.emptyCatalog => 'catEmptyCatalog',
    LibraryCatalogErrorKind.tooLarge => 'catTooLarge',
    LibraryCatalogErrorKind.network => 'netOffline',
    LibraryCatalogErrorKind.notActivatable => 'catNotActivatable',
  };

  /// Key of the translated reason why a source has no adapter.
  static String unsupportedReasonKey(LibrarySourceUnsupportedReason reason) =>
      switch (reason) {
        LibrarySourceUnsupportedReason.siteMigratedBehindChallenge =>
          'reasonSiteMigratedBehindChallenge',
        LibrarySourceUnsupportedReason.domainParked => 'reasonDomainParked',
        LibrarySourceUnsupportedReason.siteOffline => 'reasonSiteOffline',
        LibrarySourceUnsupportedReason.originUnreachable =>
          'reasonOriginUnreachable',
        LibrarySourceUnsupportedReason.adapterMissing => 'reasonAdapterMissing',
        LibrarySourceUnsupportedReason.notAidokuSource =>
          'reasonNotAidokuSource',
      };

  /// Key of the translated label of a verified source state.
  static String knownStateKey(LibrarySourceKnownState state) => switch (state) {
    LibrarySourceKnownState.working => 'stateWorking',
    LibrarySourceKnownState.siteChanged => 'stateSiteChanged',
    LibrarySourceKnownState.challenge => 'stateChallenge',
    LibrarySourceKnownState.serverUnavailable => 'stateServerUnavailable',
    LibrarySourceKnownState.offline => 'stateOffline',
    LibrarySourceKnownState.parked => 'stateParked',
    LibrarySourceKnownState.adapterMissing => 'stateAdapterMissing',
    LibrarySourceKnownState.unknown => 'stateUnknown',
  };

  /// Key of the translated name of a health check step.
  static String healthStepKey(LibrarySourceHealthStep step) => switch (step) {
    LibrarySourceHealthStep.listing => 'stepListing',
    LibrarySourceHealthStep.details => 'stepDetails',
    LibrarySourceHealthStep.chapters => 'stepChapters',
    LibrarySourceHealthStep.pages => 'stepPages',
    LibrarySourceHealthStep.image => 'stepImage',
  };

  /// Key of the translated explanation of [error] (network, source or
  /// catalogue failure); `errorUnknown` for anything else. The raw detail
  /// comes from [technicalDetail].
  static String errorKey(Object error) {
    if (error is LibraryNetworkException) return networkKey(error.kind);
    if (error is LibrarySourceException) {
      final network = error.networkError;
      if (network != null) return networkKey(network.kind);
      return sourceErrorKey(error.kind);
    }
    if (error is LibraryCatalogException) {
      final network = error.network;
      if (error.kind == LibraryCatalogErrorKind.network && network != null) {
        return networkKey(network.kind);
      }
      return catalogErrorKey(error.kind);
    }
    return 'errorUnknown';
  }

  /// Raw, untranslated diagnostic of [error] (kind, host, HTTP status, URL).
  static String technicalDetail(Object error) {
    if (error is LibraryCatalogException) {
      return <String>[
        error.toString(),
        if (error.uri != null) error.uri.toString(),
      ].join('\n');
    }
    if (error is LibraryNetworkException) {
      return <String>[
        error.toString(),
        if (error.uri != null) error.uri.toString(),
      ].join('\n');
    }
    if (error is LibrarySourceException) {
      return <String>[
        error.message,
        if (error.uri != null) error.uri.toString(),
      ].join('\n');
    }
    return error.toString();
  }


  static String forLocale(Locale locale, String key) {
    final traditional =
        locale.languageCode == 'zh' &&
        (locale.scriptCode == 'Hant' ||
            const {'TW', 'HK', 'MO'}.contains(locale.countryCode));
    return (values[traditional ? 'zh_Hant' : locale.languageCode] ??
            values['en']!)[key] ??
        values['en']!['failed']!;
  }

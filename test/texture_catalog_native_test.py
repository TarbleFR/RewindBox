def png(width=4, height=4):
    raw = b''.join(b'\x00' + bytes([(x * 37 + y * 11) & 255 for x in range(width * 4)]) for y in range(height))
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))


DDS = b'DDS ' + struct.pack('<I', 124) + bytes(72) + struct.pack('<II4s', 32, 4, b'DXT5') + bytes(40) + bytes(64)


def zip_of(path, entries):
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name, data in entries:
            archive.writestr(name, data)
    return path


def disc_header(game_id, revision):
    header = bytearray(0x440)
    header[0:6] = game_id.encode()
    header[7] = revision
    header[0x1C:0x20] = struct.pack('>I', 0xC2339F3D)
    header[0x20:0x30] = b'Synthetic disc\x00\x00'
    return bytes(header) + bytes(0x10000)


def pack(pack_id, system, engine, game, url, archive, folders, files, version='1.0', fmt=None):
    data = archive.read_bytes()
    return {
        'id': pack_id, 'system': system, 'engine': engine, 'title': f'Fixture {pack_id}', 'version': version,
        'games': [game], 'authors': ['NeoStation tests'], 'page_url': 'https://example.invalid/' + pack_id,
        'source_id': 'test:' + pack_id, 'licence': {'summary': 'Test fixture', 'redistribution': 'Generated by the test'},
        'availability': 'available',
        'download': {'automatable': True, 'format': fmt or ('7z' if archive.suffix == '.7z' else 'zip'),
                     'parts': [{'url': url, 'size': len(data), 'sha256': hashlib.sha256(data).hexdigest()}]},
        'install': {'files': files, 'bytes': 4096, 'folders': folders},
    }


def game(title, typ, scheme, value, region=None):
    entry = {'title': title, 'identities': [{'type': typ, 'scheme': scheme, 'value': value}]}
    if region:
        entry['regions'] = [region]
    return entry


def ids(index):
    return {p['id'] for p in index['packs']}


def probes(index):
    """Matching on the real catalogue: typed IDs, region-free folders, confirmations, never a title alone."""
    present = ids(index)
    wanted = []
    def probe(identity, engine, exact=(), candidate=(), absent=()):
        missing = [p for p in (*exact, *candidate, *absent) if p not in present]
        if missing:
            raise SystemExit(f'catalogue no longer has {missing}: update the probes')

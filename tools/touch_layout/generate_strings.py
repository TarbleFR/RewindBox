#!/usr/bin/env python3
"""Writes the native and Flutter catalogues of the touch-controls editor.

Source: tools/touch_layout/strings.json (twelve locales, identical keys).
Outputs:
  packages/neo_touch_layout/ios/Classes/NeoTouchLayoutStrings.m
  lib/l10n/touch_layout_locale.dart
Run with --check to fail when an output differs from what this script writes.
"""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tools/touch_layout/strings.json'
NATIVE = ROOT / 'packages/neo_touch_layout/ios/Classes/NeoTouchLayoutStrings.m'
DART = ROOT / 'lib/l10n/touch_layout_locale.dart'
LOCALES = ['en', 'fr', 'de', 'es', 'it', 'pt', 'ru', 'id', 'ja', 'ko', 'zh', 'zh_Hant']


def load():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    if data['locales'] != LOCALES:
        raise SystemExit('Unexpected locale list in strings.json')
    values = data['values']
    keys = list(values['en'])
    for locale in LOCALES:
        if list(values[locale]) != keys:
            raise SystemExit(f'{locale}: keys differ from en (order included)')
        for key, text in values[locale].items():
            if not isinstance(text, str) or not text.strip():
                raise SystemExit(f'{locale}.{key}: empty text')
            if '%' in text or '{' in text:
                raise SystemExit(f'{locale}.{key}: placeholders are not used by this catalogue')
    return keys, values


def objc(text):
    return '@"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def dart(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def native_source(keys, values):
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/touch_layout/generate_strings.py from tools/touch_layout/strings.json.',
        '// Do not edit by hand: change the JSON and run the generator.',
        '#import "Public/NeoTouchLayoutStrings.h"',
        '',
        'NSArray<NSString*>* NeoTouchLayoutLocales(void) {',
        '  return @[' + ', '.join(objc(locale) for locale in LOCALES) + '];',
        '}',
        '',
        'static NSDictionary<NSString*, NSDictionary<NSString*, NSString*>*>* NeoTouchLayoutCatalogue(void) {',
        '  static NSDictionary* catalogue;',
        '  static dispatch_once_t once;',
        '  dispatch_once(&once, ^{',
        '    catalogue = @{',
    ]
    for locale in LOCALES:
        lines.append(f'      {objc(locale)}: @{{')
        for key in keys:
            lines.append(f'        {objc(key)}: {objc(values[locale][key])},')
        lines.append('      },')
    lines += [
        '    };',
        '  });',
        '  return catalogue;',
        '}',
        '',
        'NSString* NeoTouchLayoutCanonicalLocale(NSString* identifier) {',
        '  if (![identifier isKindOfClass:NSString.class] || identifier.length == 0) return @"en";',
        '  NSString* value = [identifier stringByReplacingOccurrencesOfString:@"-" withString:@"_"];',
        '  NSString* lower = value.lowercaseString;',
        '  if ([lower hasPrefix:@"zh"]) {',
        '    if ([lower containsString:@"hant"] || [lower hasSuffix:@"_tw"] || [lower hasSuffix:@"_hk"] ||',
        '        [lower hasSuffix:@"_mo"]) return @"zh_Hant";',
        '    return @"zh";',
        '  }',
        '  NSString* language = [lower componentsSeparatedByString:@"_"].firstObject ?: @"en";',
        '  return NeoTouchLayoutCatalogue()[language] ? language : @"en";',
        '}',
        '',
        'NSDictionary<NSString*, NSString*>* NeoTouchLayoutTextsForLocale(NSString* locale) {',
        '  return NeoTouchLayoutCatalogue()[NeoTouchLayoutCanonicalLocale(locale)] ?: NeoTouchLayoutCatalogue()[@"en"];',
        '}',
        '',
        'NSString* NeoTouchLayoutText(NSString* key, NSString* locale) {',
        '  NSString* text = NeoTouchLayoutTextsForLocale(locale)[key];',
        '  return text ?: (NeoTouchLayoutCatalogue()[@"en"][key] ?: key);',
        '}',
        '',
    ]
    return '\n'.join(lines)


def dart_source(keys, values):
    lines = [
        '// Generated by tools/touch_layout/generate_strings.py from tools/touch_layout/strings.json.',
        '// Do not edit by hand: change the JSON and run the generator.',
        "import 'package:flutter/widgets.dart';",
        '',
        '/// Touch controls of the embedded Dolphin, ARMSX2 and RPCS3 engines',
        '/// (Build 484): the settings panel of the Emulators tab. The native editor',
        '/// and the in-game menus use the same texts (NeoTouchLayoutStrings.m).',
        'abstract final class TouchLayoutLocale {',
        '  static const locales = <String>[' + ', '.join(dart(locale) for locale in LOCALES) + '];',
        '',
        '  static const values = <String, Map<String, String>>{',
    ]
    for locale in LOCALES:
        lines.append(f'    {dart(locale)}: {{')
        for key in keys:
            lines.append(f'      {dart(key)}: {dart(values[locale][key])},')
        lines.append('    },')
    lines += [
        '  };',
        '',
        '  /// Catalogue key of a Flutter locale (zh_Hant for Traditional Chinese).',
        '  static String localeKey(Locale locale) {',
        "    if (locale.languageCode == 'zh') {",
        "      final script = locale.scriptCode?.toLowerCase();",
        "      final country = locale.countryCode?.toUpperCase();",
        "      if (script == 'hant' || country == 'TW' || country == 'HK' || country == 'MO') {",
        "        return 'zh_Hant';",
        '      }',
        "      return 'zh';",
        '    }',
        "    return values.containsKey(locale.languageCode) ? locale.languageCode : 'en';",
        '  }',
        '',
        '  /// Native locale identifier sent to the editor.',
        '  static String nativeLocale(Locale locale) => localeKey(locale);',
        '',
        '  static String text(String key, Locale locale) =>',
        "      values[localeKey(locale)]?[key] ?? values['en']![key] ?? key;",
        '',
        '  /// Every text prefixed "touch." for the session labels of a native',
        '  /// in-game menu (Dolphin reads its menu texts from those labels).',
        '  static Map<String, String> prefixedLabels(String localeKey) => {',
        "    for (final entry in (values[localeKey] ?? values['en']!).entries)",
        "      'touch.${entry.key}': entry.value,",
        '  };',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main():
    keys, values = load()
    outputs = {NATIVE: native_source(keys, values), DART: dart_source(keys, values)}
    if '--check' in sys.argv:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs.items()
                 if not path.exists() or path.read_text(encoding='utf-8') != text]
        if stale:
            raise SystemExit('Regenerate the touch layout catalogues: ' + ', '.join(stale))
        print(f'PASS touch layout catalogues: {len(keys)} keys x {len(LOCALES)} locales')
        return
    for path, text in outputs.items():
        path.write_text(text, encoding='utf-8')
        print('wrote', path.relative_to(ROOT))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Generates the Canvas (ES-DE) System Art capsule map.

The Canvas-Capsule custom edition (https://github.com/zenandiko/canvas-es-de)
names its images after ES-DE system folders (psx, megadrive, gamegear...),
while NeoStation looks a background up by the user's ROM folder name, which
can be any alias of a system in assets/systems/*.json. This tool maps every
alias, lowercased, to the capsule NeoStation downloads for it:

- an alias that is itself a capsule name keeps its own capsule (gx4000,
  megadrivejp, sufami...);
- any other alias takes its system's capsule: the first of the system id and
  its folders that names a capsule, or OVERRIDES for systems whose names do
  not appear in the pack.

The capsule list is the pinned revision's `theme/flat/webp` folder, recorded
in canvas-es-de-flat-webp.txt so that `--check` runs offline.

    python3 tools/system_art/canvas_es_de.py          # rewrite the Dart map
    python3 tools/system_art/canvas_es_de.py --check  # fail when it is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SYSTEMS_DIR = ROOT / "assets" / "systems"
CAPSULES_FILE = Path(__file__).with_name("canvas-es-de-flat-webp.txt")
OUTPUT = ROOT / "lib" / "services" / "system_art" / "canvas_es_de_capsules.dart"

REVISION = "12d03b1856b892497a3fa1c943888c1f542f9236"

# Systems whose id and folders name no capsule. Each value is the capsule of
# the same system, its base console, or ES-DE's equivalent collection.
OVERRIDES = {
    "all": "allgames",
    "favorites": "auto-favorites",
    "gg-hacks": "gamegear",
    "mark3": "mastersystem",
    "md-hacks": "megadrive",
    "pspminis": "psp",
    "rpgmaker": "easyrpg",
    "sfc-hacks": "sfc",
}

# NeoStation folders that are not described by assets/systems.
EXTRA_FOLDERS = {
    "collections": "custom-collections",
}


def load_capsules() -> list[str]:
    names = [line.strip() for line in CAPSULES_FILE.read_text().splitlines()]
    names = [name for name in names if name]
    if names != sorted(set(names)):
        raise SystemExit(f"{CAPSULES_FILE.name} must be sorted and unique")
    return names


def build_map() -> dict[str, str]:
    capsules = set(load_capsules())
    for target in [*OVERRIDES.values(), *EXTRA_FOLDERS.values()]:
        if target not in capsules:
            raise SystemExit(f"override target {target!r} is not a capsule")

    systems = []
    for path in sorted(SYSTEMS_DIR.glob("*.json")):
        system = json.loads(path.read_text(encoding="utf-8"))["system"]
        aliases = [system["id"], *system.get("folders", [])]
        aliases = list(dict.fromkeys(alias.lower() for alias in aliases))
        capsule = OVERRIDES.get(system["id"])
        if capsule is None:
            capsule = next((a for a in aliases if a in capsules), None)
        systems.append((system["id"], aliases, capsule))

    result: dict[str, str] = {}
    owner: dict[str, str] = {}
    for system_id, aliases, capsule in systems:
        if capsule is None:
            continue
        for alias in aliases:
            target = alias if alias in capsules else capsule
            # An alias shared by two systems belongs to the system it names
            # (pspminis is both a psp folder and the pspminis system).
            if alias in result and owner[alias] == alias:
                continue
            if alias in result and system_id != alias:
                continue
            result[alias] = target
            owner[alias] = system_id
    for folder, capsule in EXTRA_FOLDERS.items():
        result.setdefault(folder, capsule)
    return dict(sorted(result.items()))


def render(mapping: dict[str, str]) -> str:
    lines = [
        "// GENERATED by tools/system_art/canvas_es_de.py. Do not edit by hand.",
        "//",
        "// Canvas (ES-DE) System Art: lowercased NeoStation ROM folder name to",
        "// the capsule image of zenandiko/canvas-es-de at the pinned revision.",
        "",
        "const String canvasEsDeRevision =",
        f"    '{REVISION}';",
        "",
        "const Map<String, String> canvasEsDeCapsuleByFolder = {",
    ]
    for alias, capsule in mapping.items():
        key = alias.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{key}': '{capsule}',")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = render(build_map())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; rerun the tool")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

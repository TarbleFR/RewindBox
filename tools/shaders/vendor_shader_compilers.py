#!/usr/bin/env python3
"""Copy the pinned glslang and SPIRV-Cross files NeoStation compiles.

NeoStation translates RetroArch slang shaders and Dolphin post-processing
shaders to Metal on the device: glslang (GLSL -> SPIR-V) then SPIRV-Cross
(SPIR-V -> MSL). Only the files those two steps need are vendored, without
HLSL, the SPIR-V optimizer or the command-line tools.

    tools/shaders/vendor_shader_compilers.py GLSLANG_CHECKOUT SPIRV_CROSS_CHECKOUT

Both checkouts must be at the tag recorded below. The script rewrites
packages/neo_shader_kit/ios/ThirdParty/{glslang,SPIRV-Cross} and their
SOURCE.txt (tag, commit, SHA-256 of every copied file). glslang's
build_info.h is generated from CHANGES.md exactly as glslang's own
build_info.py does (version of the first release header).
"""
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THIRD_PARTY = ROOT / 'packages/neo_shader_kit/ios/ThirdParty'
TAG = 'vulkan-sdk-1.4.350.1'
GLSLANG_COMMIT = '275822a6261ee689aadb1da5f09a0ec2f058685c'
SPIRV_CROSS_COMMIT = '1a6169566c73d3da552748fc372fe2bbb856e46e'

GLSLANG_PATTERNS = (
    'LICENSE.txt',
    'glslang/Include/*.h',
    'glslang/Public/*.h',
    'glslang/MachineIndependent/*.h',
    'glslang/MachineIndependent/*.cpp',
    'glslang/MachineIndependent/preprocessor/*.h',
    'glslang/MachineIndependent/preprocessor/*.cpp',
    'glslang/GenericCodeGen/*.cpp',
    'glslang/OSDependent/osinclude.h',
    'glslang/OSDependent/Unix/ossource.cpp',
    'glslang/ResourceLimits/ResourceLimits.cpp',
    'SPIRV/GlslangToSpv.cpp', 'SPIRV/GlslangToSpv.h',
    'SPIRV/SpvBuilder.cpp', 'SPIRV/SpvBuilder.h',
    'SPIRV/Logger.cpp', 'SPIRV/Logger.h',
    'SPIRV/InReadableOrder.cpp', 'SPIRV/SpvPostProcess.cpp',
    'SPIRV/SpvTools.cpp', 'SPIRV/SpvTools.h',
    'SPIRV/disassemble.cpp', 'SPIRV/disassemble.h',
    'SPIRV/doc.cpp', 'SPIRV/doc.h',
    'SPIRV/spvIR.h', 'SPIRV/spvUtil.h', 'SPIRV/bitutils.h', 'SPIRV/hex_float.h', 'SPIRV/spirv.hpp11',
    'SPIRV/GLSL.std.450.h', 'SPIRV/GLSL.ext.*.h', 'SPIRV/NonSemantic*.h',
)
# Never needed without HLSL / without the C interface.
GLSLANG_EXCLUDE = ('glslang/MachineIndependent/glslang.y',)

SPIRV_CROSS_FILES = (
    'LICENSE', 'GLSL.std.450.h', 'NonSemanticShaderDebugInfo100.h', 'spirv.hpp',
    'spirv_cfg.cpp', 'spirv_cfg.hpp', 'spirv_common.hpp', 'spirv_cross.cpp', 'spirv_cross.hpp',
    'spirv_cross_containers.hpp', 'spirv_cross_error_handling.hpp', 'spirv_cross_parsed_ir.cpp',
    'spirv_cross_parsed_ir.hpp', 'spirv_glsl.cpp', 'spirv_glsl.hpp', 'spirv_msl.cpp', 'spirv_msl.hpp',
    'spirv_parser.cpp', 'spirv_parser.hpp',
)

BUILD_INFO = '''// Generated by tools/shaders/vendor_shader_compilers.py from glslang's
// CHANGES.md, like glslang's build_info.py and build_info.h.tmpl.
#ifndef GLSLANG_BUILD_INFO
#define GLSLANG_BUILD_INFO

#define GLSLANG_VERSION_MAJOR {major}
#define GLSLANG_VERSION_MINOR {minor}
#define GLSLANG_VERSION_PATCH {patch}
#define GLSLANG_VERSION_FLAVOR "{flavor}"

#define GLSLANG_VERSION_GREATER_THAN(major, minor, patch) \\
    ((GLSLANG_VERSION_MAJOR) > (major) || ((major) == GLSLANG_VERSION_MAJOR && \\
    ((GLSLANG_VERSION_MINOR) > (minor) || ((minor) == GLSLANG_VERSION_MINOR && \\
     (GLSLANG_VERSION_PATCH) > (patch)))))

#define GLSLANG_VERSION_GREATER_OR_EQUAL_TO(major, minor, patch) \\
    ((GLSLANG_VERSION_MAJOR) > (major) || ((major) == GLSLANG_VERSION_MAJOR && \\
    ((GLSLANG_VERSION_MINOR) > (minor) || ((minor) == GLSLANG_VERSION_MINOR && \\
     (GLSLANG_VERSION_PATCH >= (patch))))))

#define GLSLANG_VERSION_LESS_THAN(major, minor, patch) \\
    ((GLSLANG_VERSION_MAJOR) < (major) || ((major) == GLSLANG_VERSION_MAJOR && \\
    ((GLSLANG_VERSION_MINOR) < (minor) || ((minor) == GLSLANG_VERSION_MINOR && \\
     (GLSLANG_VERSION_PATCH) < (patch)))))

#define GLSLANG_VERSION_LESS_OR_EQUAL_TO(major, minor, patch) \\
    ((GLSLANG_VERSION_MAJOR) < (major) || ((major) == GLSLANG_VERSION_MAJOR && \\
    ((GLSLANG_VERSION_MINOR) < (minor) || ((minor) == GLSLANG_VERSION_MINOR && \\
     (GLSLANG_VERSION_PATCH <= (patch))))))

#endif // GLSLANG_BUILD_INFO
'''


def head(checkout):
    return subprocess.run(['git', '-C', str(checkout), 'rev-parse', 'HEAD'], check=True, capture_output=True,
                          text=True).stdout.strip()


def copy(checkout, relatives, destination):
    if destination.exists():
        shutil.rmtree(destination)
    copied = []
    for relative in sorted(set(relatives)):
        source = checkout / relative
        if not source.is_file():
            raise SystemExit(f'Missing {relative} in {checkout}')
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        copied.append(relative)
    return copied


def glslang_files(checkout):
    files = []
    for pattern in GLSLANG_PATTERNS:
        matches = sorted(path.relative_to(checkout).as_posix() for path in checkout.glob(pattern) if path.is_file())
        if not matches:
            raise SystemExit(f'No glslang file matches {pattern}')
        files += matches
    return [name for name in files if name not in GLSLANG_EXCLUDE]


def build_info(checkout):
    # build_info.py: the first "## <major>.<minor>.<patch>[-flavor] <date>" heading.
    for line in (checkout / 'CHANGES.md').read_text(encoding='utf-8').splitlines():
        match = re.match(r'^#+ +(\d+)\.(\d+)\.(\d+)(-\w+)? (\d{4}-\d{2}-\d{2})? *$', line)
        if match:
            flavor = (match.group(4) or '')[1:]
            return BUILD_INFO.format(major=match.group(1), minor=match.group(2), patch=match.group(3), flavor=flavor)
    raise SystemExit('No release heading in glslang CHANGES.md')


def write_source(destination, name, url, commit, files):
    lines = [f'{name} {TAG}', f'Repository: {url}', f'Commit: {commit}',
             'Copied by tools/shaders/vendor_shader_compilers.py (unchanged files):', '']
    for relative in files:
        digest = hashlib.sha256((destination / relative).read_bytes()).hexdigest()
        lines.append(f'{digest}  {relative}')
    (destination / 'SOURCE.txt').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    glslang = Path(sys.argv[1]).resolve()
    spirv_cross = Path(sys.argv[2]).resolve()
    if head(glslang) != GLSLANG_COMMIT:
        raise SystemExit(f'glslang checkout is not {TAG} ({GLSLANG_COMMIT})')
    if head(spirv_cross) != SPIRV_CROSS_COMMIT:
        raise SystemExit(f'SPIRV-Cross checkout is not {TAG} ({SPIRV_CROSS_COMMIT})')
    glslang_destination = THIRD_PARTY / 'glslang'
    files = copy(glslang, glslang_files(glslang), glslang_destination)
    (glslang_destination / 'glslang/build_info.h').write_text(build_info(glslang), encoding='utf-8')
    write_source(glslang_destination, 'glslang', 'https://github.com/KhronosGroup/glslang', GLSLANG_COMMIT, files)
    spirv_destination = THIRD_PARTY / 'SPIRV-Cross'
    files = copy(spirv_cross, SPIRV_CROSS_FILES, spirv_destination)
    write_source(spirv_destination, 'SPIRV-Cross', 'https://github.com/KhronosGroup/SPIRV-Cross', SPIRV_CROSS_COMMIT,
                 files)
    print(f'Vendored glslang and SPIRV-Cross {TAG} into {THIRD_PARTY.relative_to(ROOT)}')


if __name__ == '__main__':
    main()

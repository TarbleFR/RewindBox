#!/usr/bin/env python3
"""Writes the native and Flutter catalogues of the ARMSX2 HD texture packs (Build 485).

Source: tools/armsx2_textures/strings.json (twelve locales, identical keys and
placeholders).
Outputs:
  packages/armsx2_internal_bridge/ios/Classes/ARMSX2TextureStrings.m
  lib/l10n/armsx2_texture_locale.dart
Run with --check to fail when an output differs from what this script writes.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tools/armsx2_textures/strings.json'
NATIVE = ROOT / 'packages/armsx2_internal_bridge/ios/Classes/ARMSX2TextureStrings.m'
DART = ROOT / 'lib/l10n/armsx2_texture_locale.dart'
LOCALES = ['en', 'fr', 'de', 'es', 'it', 'pt', 'ru', 'id', 'ja', 'ko', 'zh', 'zh_Hant']
PLACEHOLDER = re.compile(r'\{(\w+)\}')


def load():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    if data['locales'] != LOCALES:
        raise SystemExit('Unexpected locale list in strings.json')
    values = data['values']
    keys = list(values['en'])
    for locale in LOCALES:
        if list(values[locale]) != keys:
            raise SystemExit(f'{locale}: keys differ from en (order included)')
        for key, text in values[locale].items():
            if not isinstance(text, str) or not text.strip():
                raise SystemExit(f'{locale}.{key}: empty text')
            if sorted(PLACEHOLDER.findall(text)) != sorted(PLACEHOLDER.findall(values['en'][key])):
                raise SystemExit(f'{locale}.{key}: placeholders differ from en')
            if '%' in text.replace('{percent}%', '').replace('{percent} %', ''):
                raise SystemExit(f'{locale}.{key}: printf directives are not used by this catalogue')
    return keys, values


def objc(text):
    return '@"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def dart(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def native_source(keys, values):
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/armsx2_textures/generate_strings.py from tools/armsx2_textures/strings.json.',
        '// Do not edit by hand: change the JSON and run the generator.',
        '#import "ARMSX2TextureStrings.h"',
        '#import "ARMSX2InGameLocalization.h"',
        '',
        'static NSDictionary<NSString*, NSDictionary<NSString*, NSString*>*>* ARMSX2TextureCatalogue(void) {',
        '  static NSDictionary* catalogue;',
        '  static dispatch_once_t once;',
        '  dispatch_once(&once, ^{',
        '    catalogue = @{',
    ]
    for locale in LOCALES:
        lines.append(f'      {objc(locale)}: @{{')
        for key in keys:
            lines.append(f'        {objc(key)}: {objc(values[locale][key])},')
        lines.append('      },')
    lines += [
        '    };',
        '  });',
        '  return catalogue;',
        '}',
        '',
        'NSString* ARMSX2TextureText(NSString* key, NSString* locale) {',
        '  NSDictionary* catalogue = ARMSX2TextureCatalogue();',
        '  return catalogue[ARMSX2CanonicalLocale(locale)][key] ?: catalogue[@"en"][key] ?: key;',
        '}',
        '',
        'NSString* ARMSX2TextureFormat(NSString* key, NSString* locale, NSDictionary<NSString*, id>* values) {',
        '  NSString* text = ARMSX2TextureText(key, locale);',
        '  for (NSString* name in values) {',
        '    NSString* value = [values[name] description] ?: @"";',
        '    text = [text stringByReplacingOccurrencesOfString:[NSString stringWithFormat:@"{%@}", name] withString:value];',
        '  }',
        '  return text;',
        '}',
        '',
    ]
    return '\n'.join(lines)


def dart_source(keys, values):
    lines = [
        '// Generated by tools/armsx2_textures/generate_strings.py from tools/armsx2_textures/strings.json.',
        '// Do not edit by hand: change the JSON and run the generator.',
        "import 'package:flutter/widgets.dart';",
        '',
        '/// HD texture packs of the embedded ARMSX2 engine (Build 485): the HD',
        '/// textures section of a PS2 game\'s settings. The in-game menu uses the',
        '/// same texts (ARMSX2TextureStrings.m).',
        'abstract final class Armsx2TextureLocale {',
        '  static const locales = <String>[' + ', '.join(f"'{l}'" for l in LOCALES) + '];',
        '',
        '  static const values = <String, Map<String, String>>{',
    ]
    for locale in LOCALES:
        lines.append(f"    '{locale}': {{")
        for key in keys:
            lines.append(f"      '{key}': {dart(values[locale][key])},")
        lines.append('    },')
    lines += [
        '  };',
        '',
        '  static String localeKey(Locale locale) {',
        "    if (locale.languageCode == 'zh') {",
        '      final script = locale.scriptCode?.toLowerCase();',
        '      final country = locale.countryCode?.toUpperCase();',
        "      if (script == 'hant' || country == 'TW' || country == 'HK' || country == 'MO') {",
        "        return 'zh_Hant';",
        '      }',
        "      return 'zh';",
        '    }',
        "    return locales.contains(locale.languageCode) ? locale.languageCode : 'en';",
        '  }',
        '',
        '  static String textFor(Locale locale, String key) =>',
        "      values[localeKey(locale)]?[key] ?? values['en']![key] ?? key;",
        '',
        '  static String text(BuildContext context, String key) =>',
        '      textFor(Localizations.localeOf(context), key);',
        '',
        '  static String format(',
        '    BuildContext context,',
        '    String key,',
        '    Map<String, Object?> arguments,',
        '  ) {',
        '    var value = text(context, key);',
        '    for (final item in arguments.entries) {',
        "      value = value.replaceAll('{${item.key}}', item.value?.toString() ?? '');",
        '    }',
        '    return value;',
        '  }',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main():
    keys, values = load()
    outputs = {NATIVE: native_source(keys, values), DART: dart_source(keys, values)}
    if '--check' in sys.argv:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs.items()
                 if not path.exists() or path.read_text(encoding='utf-8') != text]
        if stale:
            raise SystemExit('Regenerate with tools/armsx2_textures/generate_strings.py: ' + ', '.join(stale))
        print(f'PASS generated catalogues match strings.json ({len(keys)} keys, {len(LOCALES)} locales)')
        return
    for path, text in outputs.items():
        path.write_text(text, encoding='utf-8')
    print(f'Wrote {len(keys)} keys for {len(LOCALES)} locales')


if __name__ == '__main__':
    main()

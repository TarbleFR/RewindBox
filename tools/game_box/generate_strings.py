#!/usr/bin/env python3
"""Writes the Flutter catalogue of the 3D game box (Jaquette view).

Source: tools/game_box/strings.json (twelve locales, identical keys).
Output: lib/l10n/game_box_locale.dart
Run with --check to fail when the output differs from what this script writes
or when a locale breaks the catalogue rules: same keys and order as English,
no empty text, the same {placeholders} as English, and Traditional Chinese
different from Simplified Chinese except for the listed shared words.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tools/game_box/strings.json'
DART = ROOT / 'lib/l10n/game_box_locale.dart'
LOCALES = ['en', 'fr', 'de', 'es', 'it', 'pt', 'ru', 'id', 'ja', 'ko', 'zh', 'zh_Hant']

# Words written identically in Simplified and Traditional Chinese.
ZH_SHARED = {
    'front', 'back', 'reset', 'original', 'textSize', 'faceFront', 'faceBack',
    'faceBottom', 'edition', 'translationNotNeeded', 'region.jp', 'region.sp',
    'region.br', 'region.pt', 'region.ca', 'region.se', 'region.wor',
}

PLACEHOLDER = re.compile(r'\{(\w+)\}')


def load():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    if data['locales'] != LOCALES:
        raise SystemExit('Unexpected locale list in strings.json')
    values = data['values']
    keys = list(values['en'])
    for locale in LOCALES:
        if list(values[locale]) != keys:
            raise SystemExit(f'{locale}: keys differ from en (order included)')
        for key, text in values[locale].items():
            if not isinstance(text, str) or not text.strip():
                raise SystemExit(f'{locale}.{key}: empty text')
            expected = sorted(PLACEHOLDER.findall(values['en'][key]))
            if sorted(PLACEHOLDER.findall(text)) != expected:
                raise SystemExit(f'{locale}.{key}: placeholders differ from en {expected}')
    same = {k for k in keys if values['zh'][k] == values['zh_Hant'][k]}
    if same != ZH_SHARED:
        raise SystemExit(f'zh_Hant identical to zh for {sorted(same ^ ZH_SHARED)}')
    return keys, values


def dart(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def dart_source(keys, values):
    lines = [
        '// Generated by tools/game_box/generate_strings.py from tools/game_box/strings.json.',
        '// Do not edit by hand: change the JSON and run the generator.',
        "import 'package:flutter/widgets.dart';",
        '',
        "/// Texts of the 3D game box (Jaquette view, box inspector, back reader)",
        "/// in NeoStation's twelve languages.",
        'abstract final class GameBoxLocale {',
    ]
    for key in keys:
        if '.' not in key:
            lines.append(f'  static const {key} = {dart(key)};')
    lines += ['', '  static const List<String> locales = [' + ', '.join(dart(l) for l in LOCALES) + '];', '']
    lines.append('  static const Map<String, Map<String, String>> values = {')
    for locale in LOCALES:
        lines.append(f'    {dart(locale)}: {{')
        for key in keys:
            lines.append(f'      {dart(key)}: {dart(values[locale][key])},')
        lines.append('    },')
    lines += [
        '  };',
        '',
        '  /// Catalogue code of [locale]: Traditional Chinese for zh_Hant, Hant,',
        '  /// TW, HK and MO; English for an unknown language.',
        '  static String codeFor(Locale locale) {',
        '    var code = locale.languageCode;',
        "    if (code == 'zh_Hant') return code;",
        "    if (code == 'zh') {",
        '      final script = locale.scriptCode;',
        '      final country = locale.countryCode;',
        "      if (script == 'Hant' || country == 'TW' || country == 'HK' || country == 'MO') {",
        "        code = 'zh_Hant';",
        '      }',
        '    }',
        "    return values.containsKey(code) ? code : 'en';",
        '  }',
        '',
        '  static String forCode(String code, String key) =>',
        "      values[code]?[key] ?? values['en']![key] ?? key;",
        '',
        '  static String forLocale(Locale locale, String key) => forCode(codeFor(locale), key);',
        '',
        '  static String text(BuildContext context, String key) => forLocale(',
        "    Localizations.maybeLocaleOf(context) ?? const Locale('en'),",
        '    key,',
        '  );',
        '',
        '  static String fill(String text, Map<String, Object?> parameters) {',
        '    var value = text;',
        '    parameters.forEach((name, v) {',
        "      value = value.replaceAll('{$name}', '${v ?? ''}');",
        '    });',
        '    return value;',
        '  }',
        '',
        '  static String format(',
        '    BuildContext context,',
        '    String key,',
        '    Map<String, Object?> parameters,',
        '  ) => fill(text(context, key), parameters);',
        '',
        '  /// Name of a NeoStation language ([code] from AppLocale.supportedLanguages)',
        '  /// in the language of [context]; other codes are shown as they are.',
        '  static String languageName(BuildContext context, String code) {',
        "    final key = 'lang.$code';",
        "    return values['en']!.containsKey(key) ? text(context, key) : code;",
        '  }',
        '',
        '  /// Name of a ScreenScraper region code; unknown codes are shown in',
        '  /// capitals.',
        '  static String regionName(BuildContext context, String region) {',
        "    final key = 'region.${region.toLowerCase()}';",
        "    return values['en']!.containsKey(key) ? text(context, key) : region.toUpperCase();",
        '  }',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main():
    keys, values = load()
    output = dart_source(keys, values)
    if '--check' in sys.argv:
        if DART.read_text(encoding='utf-8') != output:
            raise SystemExit(f'{DART.relative_to(ROOT)} is stale: run tools/game_box/generate_strings.py')
        print(f'game box strings: {len(keys)} keys x {len(LOCALES)} locales up to date')
        return
    DART.write_text(output, encoding='utf-8')
    print(f'wrote {DART.relative_to(ROOT)} ({len(keys)} keys)')


if __name__ == '__main__':
    main()

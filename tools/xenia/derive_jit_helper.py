#!/usr/bin/env python3
"""Derives the dedicated XeniOS JIT helper from RewindBox's ARMSX2 helper.

The ARMSX2 helper is RewindBox's reference implementation of the integrated
JIT path: RemotePairing over manual LocalDevVPN, StikJIT attached to the
RewindBox PID by an app extension, the generic universal script (byte-equal
to RPCS3's) and the host-side nonce probe. Only identity strings differ
between engines, plus one XeniOS rule: the attach mode is decided by the Core
(IOSJitMemory::NeedsAttachedTool: TXM device on iOS 26+, region not yet
prepared in this process), not by the iOS version alone
(docs/xenios-playlist.md § JIT helper).

    python3 tools/xenia/derive_jit_helper.py           # writes the files
    python3 tools/xenia/derive_jit_helper.py --check   # fails on any drift

Dedicated identities: bundle `com.neogamelab.neostation.xeniajithelper`,
target `XeniaJITHelper`, marker `NeoStationXeniaJITHelper`, request type
`com.neogamelab.neostation.xenia-jit-request`, channel `neostation/xenia_jit`,
script `xenia-universal.js`, library folder `NeoStationXeniaStikJIT`.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# (template, output)
FILES = (
    ('native/armsx2_internal_helper/Info.plist',
     'native/xenia_internal_helper/Info.plist'),
    ('native/armsx2_internal_helper/Armsx2JITExtensionEntry.swift',
     'native/xenia_internal_helper/XeniaJITExtensionEntry.swift'),
    ('packages/armsx2_jit_helper/ios/armsx2_jit_helper.podspec',
     'packages/xenia_jit_helper/ios/xenia_jit_helper.podspec'),
    ('packages/armsx2_jit_helper/ios/Classes/Armsx2JITRequestHandlerBase.swift',
     'packages/xenia_jit_helper/ios/Classes/XeniaJITRequestHandlerBase.swift'),
    ('packages/armsx2_jit_helper/ios/Resources/armsx2-universal.js',
     'packages/xenia_jit_helper/ios/Resources/xenia-universal.js'),
    ('packages/armsx2_internal_bridge/ios/Classes/Armsx2JitBridgePlugin.h',
     'packages/xenia_internal_bridge/ios/Classes/XeniaJitBridgePlugin.h'),
    ('packages/armsx2_internal_bridge/ios/Classes/Armsx2JitBridgePlugin.mm',
     'packages/xenia_internal_bridge/ios/Classes/XeniaJitBridgePlugin.mm'),
    ('build-utils/configure_armsx2_ios.py',
     'build-utils/configure_xenia_ios.py'),
)

# XeniOS-specific edits, applied to the template text before renaming.
# Each must match exactly once.
PATCHES = {
    'packages/armsx2_jit_helper/ios/Classes/Armsx2JITRequestHandlerBase.swift': (
        ('''      // ARMSX2 selects its mirrored Universal arena by OS version, not TXM
      // detection. Even a non-TXM device on iOS 26 needs this script running
      // when Core constructors request their executable regions.
''', '''      // XeniOS: the bridge asks the Core (IOSJitMemory::NeedsAttachedTool:
      // TXM device on iOS 26+, code region not yet prepared in this process).
      // With it the script stays attached until the Core's own prepare
      // (x16=1) and detach (x16=0) requests; without it, a classic attach
      // that leaves CS_DEBUGGED.
'''),
    ),
    'packages/armsx2_internal_bridge/ios/Classes/Armsx2JitBridgePlugin.mm': (
        ('''static BOOL ARMSX2RequiresCoreHandshake(void) {
  if (@available(iOS 26.0, *)) return YES;
  return NO;
}''', '''// XeniOS: the Core decides (XeniaInternalBridgePlugin `jitState`, from
// IOSJitMemory::NeedsAttachedTool) and Dart passes it as
// `requiresCoreHandshake`; this is only the default when it is absent.
static BOOL ARMSX2RequiresCoreHandshake(void) {
  if (@available(iOS 26.0, *)) return YES;
  return NO;
}'''),
        ('''    session.requiresCoreHandshake = ARMSX2RequiresCoreHandshake();''',
         '''    session.requiresCoreHandshake = [args[@"requiresCoreHandshake"] isKindOfClass:NSNumber.class]
        ? [args[@"requiresCoreHandshake"] boolValue]
        : ARMSX2RequiresCoreHandshake();'''),
        ('''URLByAppendingPathComponent:@"PS2" isDirectory:YES];''',
         '''URLByAppendingPathComponent:@"Xbox360" isDirectory:YES];'''),
    ),
    'packages/armsx2_jit_helper/ios/armsx2_jit_helper.podspec': (
        ("App-extension implementation used only by NeoStation's embedded PlayStation 2",
         "App-extension implementation used only by RewindBox's embedded Xbox 360"),
    ),
}

# Identity renames, in order (longest/most specific first).
RENAMES = (
    # Objective-C classes share one runtime namespace even with RTLD_LOCAL:
    # the plugin's classes carry the RB prefix so none can meet a class of
    # the XeniOS Core (docs/xenios-playlist.md § Native boundary).
    ('ARMSX2JitSession', 'RBXeniaJitSession'),
    ('NeoStationARMSX2', 'NeoStationXenia'),
    ('ARMSX2JITHelper', 'XeniaJITHelper'),
    ('armsx2jithelper', 'xeniajithelper'),
    ('ARMSX2', 'Xenia'),
    ('Armsx2', 'Xenia'),
    ('armsx2', 'xenia'),
)

HEADER = {
    '.swift': '// Generated by tools/xenia/derive_jit_helper.py from {template}; edit the template.\n',
    '.mm': '// Generated by tools/xenia/derive_jit_helper.py from {template}; edit the template.\n',
    '.h': '// Generated by tools/xenia/derive_jit_helper.py from {template}; edit the template.\n',
    '.js': '// Generated by tools/xenia/derive_jit_helper.py from {template}; edit the template.\n',
    '.podspec': '# Generated by tools/xenia/derive_jit_helper.py from {template}; edit the template.\n',
    '.py': '# Generated by tools/xenia/derive_jit_helper.py from {template}; edit the template.\n',
}


def derive(template: str) -> str:
    text = (ROOT / template).read_text(encoding='utf-8')
    for old, new in PATCHES.get(template, ()):
        if text.count(old) != 1:
            raise SystemExit(f'{template}: XeniOS patch no longer matches exactly once:\n{old[:120]}')
        text = text.replace(old, new, 1)
    for old, new in RENAMES:
        text = text.replace(old, new)
    suffix = Path(template).suffix
    header = HEADER.get(suffix)
    if header is None:  # Info.plist: no comment line before the XML declaration.
        return text
    first, sep, rest = text.partition('\n')
    if first.startswith('#!'):  # keep the shebang first
        return first + sep + header.format(template=template) + rest
    return header.format(template=template) + text


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for template, output in FILES:
        expected = derive(template)
        target = ROOT / output
        if args.check:
            if not target.is_file() or target.read_text(encoding='utf-8') != expected:
                drift.append(output)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding='utf-8')
        if template.endswith('.py'):
            target.chmod(0o755)
    if drift:
        print('XeniOS JIT helper drifted from its ARMSX2 templates: ' + ', '.join(drift))
        print('Run python3 tools/xenia/derive_jit_helper.py and review the diff.')
        return 1
    print('XeniOS JIT helper ' + ('matches its templates.' if args.check else 'written.'))
    return 0


if __name__ == '__main__':
    sys.exit(main())

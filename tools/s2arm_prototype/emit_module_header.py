#!/usr/bin/env python3
"""Emit the rewritten synthetic module as a C header for the device probe.

Usage: emit_module_header.py <rewriter output dir> <header to write>
The header is generated data: the rewriter's output for make_synth_nso.py.
"""
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import make_synth_nso as synth

BLOCK = 32


def main():
    out, target = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    image = (out / 'main.patched.bin').read_bytes()
    header = {}
    for line in (out / 'main.fixups.tsv').read_text().splitlines():
        if line.startswith('# '):
            key, _, value = line[2:].partition('\t')
            header.setdefault(key, value)
    ranges, start = [], None
    for at in range(0, len(image) + BLOCK, BLOCK):
        used = any(image[at:at + BLOCK])
        if used and start is None:
            start = at
        elif not used and start is not None:
            ranges.append((start, image[start:at]))
            start = None
    lines = [
        '// Generated by tools/s2arm_prototype/emit_module_header.py. Do not edit.',
        '// Output of the S2Arm rewriter (see tools/s2arm_prototype/pin.json) for the synthetic',
        '// module of tools/s2arm_prototype/make_synth_nso.py. No game content.',
        '#pragma once',
        '#include <stdint.h>',
        f'#define RB_S2ARM_SYNTH_SHA256 "{hashlib.sha256(image).hexdigest()}"',
        f'#define RB_S2ARM_SYNTH_FILE_SIZE {len(image):#x}u',
        f'#define RB_S2ARM_SYNTH_LOAD_BIAS {int(header.get("LOAD_BIAS", "0"), 16):#x}u',
        f'#define RB_S2ARM_SYNTH_TEXT_END {int(header["TEXT_END"], 16):#x}u',
        f'#define RB_S2ARM_SYNTH_KEY_PAGE_OFF {int(header["KEY_PAGE_OFF"], 16):#x}u',
        f'#define RB_S2ARM_SYNTH_PATCH_OFF {int(header["PATCH_OFF"], 16):#x}u',
        f'#define RB_S2ARM_SYNTH_ENTRY {synth.CODE_AT:#x}u',
        f'#define RB_S2ARM_SYNTH_BRK_OFF {synth.BRK_OFFSET:#x}u',
    ]
    for name in ('K18', 'KTLS', 'KTLR', 'KGATE'):
        lines.append(f'#define RB_S2ARM_SYNTH_{name}_IDX {int(header[f"KEY_{name}_IDX"])}u')
    for index, (_, data) in enumerate(ranges):
        rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
        lines.append(f'static const uint8_t rb_s2arm_synth_r{index}[] = {{\n  ' + ',\n  '.join(rows) + '};')
    lines.append('static const struct { uint32_t offset, length; const uint8_t *bytes; } rb_s2arm_synth_ranges[] = {')
    lines += [f'  {{{offset:#x}, {len(data):#x}, rb_s2arm_synth_r{index}}},' for index, (offset, data) in enumerate(ranges)]
    lines.append('};')
    lines.append('// kind: 0 = svc (arg = number), 1 = cntpct (arg = register)')
    lines.append('static const struct { uint32_t ret, orig; int kind, arg; } rb_s2arm_synth_gates[] = {')
    for line in (out / 'main.gates.tsv').read_text().splitlines():
        fields = line.split()
        if len(fields) >= 4 and not line.startswith('#'):
            kind = {'svc': 0, 'cntpct': 1}[fields[1]]
            lines.append(f'  {{{int(fields[0], 16):#x}, {int(fields[3], 16):#x}, {kind}, {int(fields[2])}}},')
    lines.append('};')
    target.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
